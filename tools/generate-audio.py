#!/usr/bin/env python3
"""Generate reusable German MP3 clips with Piper's free local German voice.

Preview the corpus: python3 tools/generate-audio.py
Generate clips: python3 tools/generate-audio.py --generate
"""

import argparse
import ast
import html
import json
import re
from concurrent.futures import ProcessPoolExecutor
from multiprocessing import get_context
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / "audio"
INDEX = ROOT / "assets" / "audio-index.js"
MODEL = ROOT / "tools" / "models" / "de_DE-thorsten-medium.onnx"
VOICE = None
LITERAL = r'("(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\')'
FIELD = re.compile(r"\b(de|ex)[\"']?\s*:\s*" + LITERAL)
OBJECT = re.compile(r"\{[^{}]*\}", re.DOTALL)


def clean(value):
    value = re.sub(r"<br\s*/?\s*>", " ", value, flags=re.IGNORECASE)
    value = html.unescape(re.sub(r"<[^>]*>", "", value))
    value = re.sub(r"\([^)]*\)", "", value)
    value = re.sub(r"\s*/\s*", ", ", value)
    value = re.sub(r"[+]\s*(?:Akk|Dat)\w*", "", value)
    return " ".join(value.replace("…", "").split())


def clip_id(value):
    # Match audio.js: FNV-1a over JavaScript UTF-16 code units.
    number = 2166136261
    raw = value.encode("utf-16-le")
    for pos in range(0, len(raw), 2):
        number ^= raw[pos] | raw[pos + 1] << 8
        number = number * 16777619 & 0xFFFFFFFF
    return f"{number:08x}"


def decode(literal):
    if literal[0] == '"':
        return json.loads(literal)
    return ast.literal_eval(literal)


def collect():
    texts = set()
    for path in sorted((ROOT / "classes").glob("*.js")):
        source = path.read_text(encoding="utf-8")
        for match in FIELD.finditer(source):
            value = clean(decode(match.group(2)))
            if value:
                texts.add(value)
        # The main vocabulary table reads the word and its example together.
        for match in OBJECT.finditer(source):
            fields = {}
            for field in FIELD.finditer(match.group()):
                fields[field.group(1)] = decode(field.group(2))
            if fields.get("de") and fields.get("ex"):
                texts.add(clean(fields["de"] + ". " + fields["ex"]))
    texts = sorted(texts)
    ids = {}
    for value in texts:
        key = clip_id(value)
        if key in ids and ids[key] != value:
            raise ValueError(f"Hash collision: {ids[key]!r} and {value!r}")
        ids[key] = value
    return texts


def load_voice(model):
    global VOICE
    from piper import PiperVoice
    VOICE = PiperVoice.load(model)


def synthesize(value):
    import lameenc
    encoder = lameenc.Encoder()
    encoder.set_bit_rate(48)
    encoder.set_channels(1)
    encoder.set_quality(2)
    result = bytearray()
    for chunk in VOICE.synthesize(value):
        encoder.set_in_sample_rate(chunk.sample_rate)
        result.extend(encoder.encode(chunk.audio_int16_bytes))
    result.extend(encoder.flush())
    if not result:
        raise RuntimeError(f"Piper produced no audio for {value!r}")
    return bytes(result)


def write_index():
    keys = sorted(path.stem for path in AUDIO.glob("*.mp3")) if AUDIO.exists() else []
    INDEX.write_text("/* Generated by tools/generate-audio.py. */\nwindow.B2_AUDIO_INDEX = " +
                     json.dumps(keys, separators=(",", ":")) + ";\n", encoding="utf-8")
    return len(keys)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true", help="Run Piper and save MP3 files")
    parser.add_argument("--model", type=Path, default=MODEL, help="Path to a German Piper ONNX voice")
    parser.add_argument("--limit", type=int, help="Generate only this many clips for a pilot")
    parser.add_argument("--jobs", type=int, default=2, help="Parallel voice workers (default: 2)")
    args = parser.parse_args()
    texts = collect()
    pending = [value for value in texts if not (AUDIO / (clip_id(value) + ".mp3")).exists()]
    if args.limit is not None:
        pending = pending[:args.limit]
    print(f"{len(texts)} unique clips; {len(pending)} to generate; {sum(map(len, pending)):,} input characters")
    if not args.generate:
        return
    if not args.model.exists() or not args.model.with_suffix(".onnx.json").exists():
        parser.error("German Piper model missing; download de_DE-thorsten-medium first (see README)")
    if args.jobs < 1:
        parser.error("--jobs must be at least 1")
    AUDIO.mkdir(exist_ok=True)
    try:
        with ProcessPoolExecutor(max_workers=args.jobs, mp_context=get_context("fork"),
                                 initializer=load_voice, initargs=(args.model,)) as pool:
            for number, (value, data) in enumerate(zip(pending, pool.map(synthesize, pending, chunksize=4, buffersize=16)), 1):
                destination = AUDIO / (clip_id(value) + ".mp3")
                temp = destination.with_suffix(".tmp")
                temp.write_bytes(data)
                temp.replace(destination)
                if number % 100 == 0 or number == len(pending):
                    print(f"Saved {number}/{len(pending)} new clips", flush=True)
                if number % 250 == 0:
                    write_index()
    finally:
        print(f"Indexed {write_index()} saved clips")


if __name__ == "__main__":
    main()
